"""Build js/complements.js (window.HEALTH_COMPLEMENTS) from docs/health-complements.json (TrackDaddy analysis).

Only complements that exist in the app catalog (js/products.js) are kept, strongest first; the median
reorder cycle is kept per product. Re-run after a new analysis:  python3 tools/build_complements.py
"""
import json, re
d = json.load(open('docs/health-complements.json'))
prod = open('js/products.js').read()
by_num = {m.group(2): m.group(1) for m in re.finditer(r"id: '(\w+)', sku: (\d+)", prod)}
out = {}
for app_id, v in d.items():
    if app_id.startswith('_') or not isinstance(v, dict):
        continue
    comps = []
    for c in v.get('complements', []):
        cid = by_num.get(str(c.get('id')))
        if cid and cid != app_id and c.get('in_app_catalog', True):
            comps.append({'id': cid, 'lift': c.get('lift'), 'confidence': c.get('confidence')})
    out[app_id] = {'complements': comps, 'median_reorder_days': v.get('median_reorder_days')}
js = ('// generated by tools/build_complements.py from docs/health-complements.json (TrackDaddy co-purchase analysis)\n'
      'window.HEALTH_COMPLEMENTS = ' + json.dumps(out, indent=1) + ';\n')
open('js/complements.js', 'w').write(js)
print(json.dumps({k: [c['id'] for c in v['complements']] for k, v in out.items()}))
