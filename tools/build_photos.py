"""Write js/photos.js listing exercise / hero photos present in img/ (run after adding photos)."""
import os, json
ex = sorted(f[:-4] for f in os.listdir('img/ex') if f.endswith('.jpg'))
hero = sorted(f[:-4] for f in os.listdir('img/hero') if f.endswith('.jpg')) if os.path.isdir('img/hero') else []
open('js/photos.js', 'w').write('/* generated by tools/build_photos.py */\nwindow.PHOTOS = ' + json.dumps({'ex': ex, 'hero': hero}) + ';\n')
print(len(ex), 'exercise photos,', len(hero), 'hero photos')
