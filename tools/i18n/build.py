"""Build the shipped dictionaries from the validated translations.
usage: python3 tools/i18n/build.py
  tools/i18n/out/<lang>.json → lang/<lang>.js            (window.I18N_DICT, loaded by js/i18n.js)
                             → supabase/functions/_shared/reminder_i18n.json  (reminder texts for the server)
"""
import glob, json, os, re
src = json.load(open('tools/i18n/source.json'))
os.makedirs('lang', exist_ok=True)
# the reminder texts the server sends (same key scheme: numbers → {0})
txt = open('supabase/functions/_shared/reminder_plan.ts', encoding='utf-8').read()
body = txt[txt.index('export const TEXT'):txt.index('};', txt.index('export const TEXT'))]
def key(s):
    n = [0]
    def rep(m): n[0] += 1; return '{%d}' % (n[0] - 1)
    return re.sub(r'\d+(?:[.,:]\d+)*', rep, re.sub(r'\s+', ' ', s).strip())
rkeys = sorted({key(s) for s in re.findall(r"'([^']+)'", body) if re.search(r'[A-Za-z]{2}', s)})
server = {'en': {}}
for f in sorted(glob.glob('tools/i18n/out/*.json')):
    lang = os.path.basename(f)[:-5]
    if '.' in lang: continue
    d = json.load(open(f, encoding='utf-8'))
    d = {k: v for k, v in d.items() if k in set(src) and v and v != k}
    with open('lang/%s.js' % lang, 'w', encoding='utf-8') as o:
        o.write('// generated by tools/i18n/build.py – edit tools/i18n/out/%s.json\nwindow.I18N_DICT=' % lang)
        o.write(json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n')
    server[lang] = {k: d[k] for k in rkeys if k in d}
    print(lang, len(d), 'entries,', len(server[lang]), '/', len(rkeys), 'reminder texts')
json.dump(server, open('supabase/functions/_shared/reminder_i18n.json', 'w'), ensure_ascii=False, indent=0)
