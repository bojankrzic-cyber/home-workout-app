"""Write js/voiceclips.js listing the recorded coach clips in audio/voice (keys = file names)."""
import os
keys = sorted(f[:-4] for f in os.listdir('audio/voice') if f.endswith('.mp3'))
with open('js/voiceclips.js', 'w') as f:
    f.write('// generated by tools/voice/build_manifest.py – recorded coach clips in audio/voice/\n')
    f.write('window.VOICE_CLIPS = ' + repr(keys).replace("'", '"') + ';\n')
print(len(keys), 'clips')
